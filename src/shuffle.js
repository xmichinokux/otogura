'use strict';

/**
 * シャッフルの選び方。
 *
 * ■ 本人の希望（2026-08-24）
 * > 現在のアップルのシャッフル機能は再生回数が多いものを選びがちなのが嫌なので、
 * > 自分が忘れてるような再生回数が少ない曲を選ぶ確率が高いものにしてほしい
 *
 * ■ どう実現しているか
 * 「均等にランダム」ではなく、**再生回数が少ないほど重い**くじにする。
 *
 *   重み = 1 / (再生回数 + 1)
 *
 *   0 回 … 1.00   ← 一度も聴いていない曲がいちばん出やすい
 *   1 回 … 0.50
 *   2 回 … 0.33
 *   9 回 … 0.10   ← 0 回の曲の 10 分の 1 しか出ない
 *
 * 「聴いた曲が出なくなる」のではなく「出にくくなる」だけ。締め出さない。
 *
 * ■ 同じ曲が続けて出ないようにする
 * 重みだけで選ぶと、同じ曲が連続で当たることがある。
 * **この巡で流した曲は、いったん候補から外す**（全部流し終えたら巡を空にする）。
 */

/** 再生回数から、くじの重みを出す */
function 重み(回数) {
  const n = Number.isFinite(回数) && 回数 > 0 ? 回数 : 0;
  return 1 / (n + 1);
}

/**
 * 次の1曲を選ぶ。
 *
 * @param 候補    選べる曲のパスの配列
 * @param 回数表  { パス: 再生回数 }
 * @param 済み    この巡ですでに流したパスの集合
 * @param 乱数    0以上1未満（試験のため差し替えられるようにしてある）
 * @returns 選ばれたパス。候補が空なら null
 */
function 次を選ぶ(候補, 回数表 = {}, 済み = new Set(), 乱数 = Math.random) {
  if (!候補.length) return null;

  // この巡でまだ流していないものから選ぶ。全部流し終えていたら全体から
  let 残り = 候補.filter((p) => !済み.has(p));
  if (!残り.length) 残り = [...候補];

  const 重みの列 = 残り.map((p) => 重み(回数表[p]));
  const 合計 = 重みの列.reduce((a, b) => a + b, 0);
  if (合計 <= 0) return 残り[Math.floor(乱数() * 残り.length)];

  let くじ = 乱数() * 合計;
  for (let i = 0; i < 残り.length; i += 1) {
    くじ -= 重みの列[i];
    if (くじ <= 0) return 残り[i];
  }
  return 残り[残り.length - 1];        // 丸め誤差の逃げ道
}

/** この巡を全部流し終えたか（＝「最後まで行った」の判定） */
function 巡が終わったか(候補, 済み) {
  return 候補.length > 0 && 候補.every((p) => 済み.has(p));
}

