/**
 * タグを読む。読めなければ null。
 *
 * ★アートワークは読まない（skipCovers）。
 * 理由は速さではなく、**全曲ぶん持つと 17.8 GB になり、アプリが落ちる**から。
 * 絵は再生する 1 曲だけ、そのときに読む（アートワークを読む を使う）。
 *
 * ★速さの効果は、当初「12 倍」と書いていたが**測り違い**だった。
 * 冷えたファイルで、順番を入れ替えて 2 回ずつ測り直した結果（2026-08-25）:
 *
 *   絵を読まない 20.6 ms/曲 ／ 絵も読む 20.6 ms/曲 → **差 0%**
 *
 * 「12 倍」は、2 回目の測定が OS のキャッシュに当たっていただけだった。
 * ★同じ標本を続けて測ると、あとの回が必ず速く出る。**別の冷えた標本で比べること。**
 */
/**
 * ★ID3v2.3 に入っている値を優先して取り出す。
 *
 * ■ なぜ要るか（2026-08-25 実測。**私の組み合わせ間違い**）
 * 本人のライブラリに、**ID3v2.3 と ID3v2.4 の両方が入った MP3** があった。
 *
 *   ID3v2.3 : TCON = "Thrash Metal"   ← node-id3 が書いたほう
 *   ID3v2.4 : TCON = "????"           ← music-metadata が優先して読むほう
 *
 * このアプリは **書くのに node-id3、読むのに music-metadata** を使っている。
 * node-id3 は ID3v2.3 にしか書かない。music-metadata は版の新しい 2.4 を優先する。
 * だから「書き込みました」と出るのに、**一覧はいつまでも変わらない。**
 * しかも書き込み自体は成功しているので、失敗として出てこない。
 *
 * 直し方: **自分が書いたほう（ID3v2.3）を先に見る。**
 * 2.3 に無ければ、これまでどおり common の値を使う。
 *
 * ★2 つの道具を組み合わせるときは、**同じものを見ているか確かめること。**
 * 書けたかどうかは「書いた側」ではなく「読む側」で確かめないと分からない。
 */
function v23から取る(meta, id) {
  const 並び = meta?.native?.['ID3v2.3'];
  if (!Array.isArray(並び)) return null;
  const 見つけた = 並び.find((x) => x.id === id);
  if (!見つけた) return null;
  const v = 見つけた.value;
  if (typeof v === 'string') return v;
  if (v && typeof v.text === 'string') return v.text;      // TXXX 等
  return null;
}

async function readTags(file) {
  try {
    const mm = await メタ読み込み();
    const meta = await mm.parseFile(file, { duration: true, skipCovers: true });
    const c = meta.common ?? {};
    /*
     * ★曲名・演者・アルバムは、これまでどおり music-metadata に任せる。
     *
     * 最初これらも ID3v2.3 優先にしたが、**2,000 曲で 2 件、日本語が壊れた**（実測）。
     *   "無限の坂" → "³ÀÌâ"
     * ID3v2.3 は文字コードの決め方が弱く、music-metadata のほうが上手く読む。
     * ジャンルだけは 0 件だったので、そこだけ優先する（下の genre を参照）。
     *
     * ★測ってから決めた。全部を 2.3 優先にしていたら、日本語の曲名を壊していた。
     */
    const title = (c.title ?? '').trim();
    const artist = (c.artist ?? '').trim();
    const album = (c.album ?? '').trim();

    return {
      path: file,
      /*
       * ★曲名が無くても一覧に出す。隠すかどうかは画面側の設定にする。
       * 以前はここで null を返して**黙って消していた。**
       * 本人が「タグの無い曲を隠す／隠さないを選びたい」と言ったので、
       * 判断は使う人に渡し、ここは事実だけを返す。
       */
      title: title || path.basename(file, path.extname(file)),
      artist: artist || 'Unknown',
      album: album || 'Unknown',
      /*
       * ジャンルは 3 カラムの左端。空のときは本人の指定で「ジャンル名無し」。
       *
       * ★ここだけ ID3v2.3 を優先する。
       * 「ジャンルを直したのに、いつまでも ???? のまま」の原因がここだった。
       * 実測（2,000 曲）: ジャンルを 2.3 優先にしても、値が変わったのは 0 件。
       * 曲名は 2 件壊れたので、そちらは元のままにしてある。
       */
      genre: (
        v23から取る(meta, 'TCON')
        ?? (Array.isArray(c.genre) ? (c.genre[0] ?? '') : (c.genre ?? ''))
      ).trim() || 'ジャンル名無し',
      track: typeof c.track?.no === 'number' ? c.track.no : null,
      duration: meta.format?.duration ?? null,
      /*
       * ★鳴らせるか。**一覧からは消さない**（本人の選択 2026-08-28）。
       * 出したうえで、押したときに理由を言う。
       * ここは事実だけを返し、どう見せるかは画面側が決める。
       *
       * ★ここを読むのに、追加のファイル読み込みは要らない。
       * meta は上ですでに読んでいるので、見るだけ。
       */
      鳴らせる: 鳴らせるか(meta.format?.codec),
      codec: meta.format?.codec ?? null,
      /**
       * ★タグが入っているか。バンドの試作品を隠すために使う。
       * 曲名が無い、または（アーティストもアルバムも無い）なら「タグなし」。
       * 書き出したままの音源は、たいていこの形になる。
       */
      タグあり: !!title && !!(artist || album),
    };
  } catch {
    return null;                             // 壊れている
  }
}

/**
 * 再生する 1 曲ぶんのアートワークだけ読む。
 * ★一覧では読まない。全曲ぶん持つと 17.8 GB になる（実測）。
 */
async function アートワークを読む(file) {
  try {
    const mm = await メタ読み込み();
    const meta = await mm.parseFile(file, { duration: false });
    const p = meta.common?.picture?.[0];
    if (!p) return null;
    return `data:${p.format};base64,${Buffer.from(p.data).toString('base64')}`;
  } catch {
    return null;
  }
}

/**
 * ★読み方の版。**タグの読み方を変えたら、必ず 1 つ増やすこと。**
 *
 * 覚え書きは「ファイルが変わっていなければ読み直さない」作りなので、
 * **読む側を直しても、覚えている値は古いまま残る。**
 * 実際にそうなった（2026-08-25）:
 *   ジャンルの読み方を直したのに、覚え書きの 14 件が ???? のままだった。
 * ファイルは変わっていないので、いつまでも読み直されない。
 *
 * 版を変えると目印が全部食い違うので、次の走査で読み直される。
 *
 *   1 … 最初
 *   2 … ジャンルを ID3v2.3 優先で読むようにした（2026-08-25）
 */
const 読み方の版 = 2;

/**
 * ★.m4a だけ、別に数える（2026-08-28）。
 *
 *   1 … .m4a を拾うようにした
 *   2 … 鳴らせるか（ALAC かどうか）も見るようにした
 *
 * ■ なぜ全体の版を上げないか
 * 版を上げると**その形式の覚え書きが全部食い違い、読み直しになる。**
 * 読み方を変えたのは .m4a だけなのに、全体の版を上げると
 * **mp3 86,074 曲まで読み直すことになる**（冷えたファイルで 36 ms/曲 ≒ 50 分）。
 * .m4a だけなら 8,885 曲 ≒ 5 分で済む。
 *
 * ★「読み方を変えた形式だけ読み直す」。変えていないものは触らない。
 */
const m4aの読み方の版 = 2;

/** ファイルの目印。これが同じなら、タグを読み直さなくてよい */
async function 目印(file) {
  try {
    const st = await fs.stat(file);
    const 版 = path.extname(file).toLowerCase() === '.m4a'
      ? `v${読み方の版}m${m4aの読み方の版}`
      : `v${読み方の版}`;
    return `${版}:${st.mtimeMs}:${st.size}`;
  } catch {
    return null;
  }
}

/**
 * フォルダ群を走査して一覧を作る。
 *
 * @param folders  スキャン対象
 * @param hidden   一覧から外したファイルのパス（ファイルは消していない）
 * @param 覚え書き  前回の結果 { [path]: { 目印, track } }。同じなら読み直さない
 * @param 進み      進み具合を知らせる関数（{ 段階, 済み, 全体 }）
 * @param 途中経過  見つかったそばから渡す関数（tracks の配列）
 * @param 覚え途中  覚え書きの増えたぶんを渡す関数（{ [path]: {目印, track} }）
 *
 * ★覚え書きを最後にまとめて返すだけだと、**途中で閉じた回はまるごと捨てられる。**
 * 実地でそうなっていた（2026-08-25）: 171,085 件の覚え書きが古い形式のまま残り、
 * 起動のたびに全曲を読み直していた。171,085 曲では完走まで数分かかるので、
 * その前に閉じれば、次もまた最初から。**永久に追いつかない。**
 */
async function scanLibrary(folders, hidden = [], 覚え書き = {}, 進み = null, 途中経過 = null, 覚え途中 = null) {
  const 知らせる = (n) => 進み && 進み({ 段階: '数えています', 済み: n, 全体: null });

  const files = [];
  for (const dir of folders) await collectTracks(dir, files, 0, 知らせる);
  if (進み) 進み({ 段階: '数えました', 済み: files.length, 全体: files.length });

  const skip = new Set(hidden);
  const 見る = files.filter((f) => !skip.has(f));

  /*
   * ★外した曲の「覚え書き」までは捨てない（2026-08-25 実地）。
   *
   * 走査の最後に覚え書きを丸ごと書き換える作りなので、
   * 外した曲は一覧から消えるだけでなく、**記録ごと消えていた。**
   * すると「戻す」を押しても中身が無く、読み直しの順番待ちになる。
   * 実際、戻したはずの 3 曲が覚え書きから消えていた。
   *
   * 外すのは「一覧に出さない」だけの約束で、忘れる約束ではない。
   * ファイルが実在するなら、前の記録をそのまま持ち越す（読み直しはしない）。
   */
  const 外したぶんの覚え書き = {};
  for (const f of files) {
    if (!skip.has(f)) continue;
    const 前 = 覚え書き[f];
    if (前) 外したぶんの覚え書き[f] = 前;
  }

  /*
   * ★はじめて見るファイルを先に読む（2026-08-25 実地）。本人からの報告:
   *   > ライブラリのフォルダーにデータを追加して再スキャンしたんですが
   *   > 読み込まれないです
   *
   * 実測すると、足されたのは **171,096 曲のうち 4 曲**だった。
   * 見つけること自体は 1 秒でできている。にもかかわらず出てこないのは、
   * **その 4 曲が読まれる順番が、17 万曲の最後のほうだったから。**
   * 全部読み終わるまで 100 分近くかかる。
   *
   * 覚え書きに無いファイルを先頭に回せば、**数秒で一覧に出る。**
   * 残りの読み直しは、そのあと裏で続ければいい。
   *
   * ★並べ替えに stat は使わない（17 万回の stat は遅い）。
   * 「覚え書きに載っているか」だけで分ける。これは表を引くだけなので一瞬。
   */
  const はじめて = [];
  const 見たことある = [];
  for (const f of 見る) (覚え書き[f] ? 見たことある : はじめて).push(f);
  const 対象 = はじめて.concat(見たことある);
  if (進み && はじめて.length) {
    進み({ 段階: 'はじめて見るものを先に読みます', 済み: 0, 全体: はじめて.length });
  }

  const tracks = [];
  const 新しい覚え書き = {};
  let unreadable = 0;
  let 使い回し = 0;
  let 済み = 0;
  let 溜め = [];
  let 覚え溜め = {};
  let 覚え溜め数 = 0;

  /** 1 本ぶん */
  const 一本 = async (f) => {
    const m = await 目印(f);
    const 前 = 覚え書き[f];
    let t;
    if (前 && m && 前.目印 === m) {
      t = 前.track;                            // ★変わっていないので読み直さない
      使い回し += 1;
    } else {
      t = await readTags(f);
    }
    if (t) {
      tracks.push(t);
      溜め.push(t);
      if (m) {
        新しい覚え書き[f] = { 目印: m, track: t };
        覚え溜め[f] = { 目印: m, track: t };
        覚え溜め数 += 1;
      }
    } else {
      unreadable += 1;
    }
    済み += 1;
    if (進み && 済み % 200 === 0) 進み({ 段階: '読んでいます', 済み, 全体: 対象.length });
    // ★少しずつ返す。全部そろうまで待たせない
    if (途中経過 && 溜め.length >= 500) { 途中経過(溜め); 溜め = []; }
    // ★覚え書きも途中で渡す。閉じられても、そこまでは残る
    if (覚え途中 && 覚え溜め数 >= 2000) { 覚え途中(覚え溜め); 覚え溜め = {}; 覚え溜め数 = 0; }
  };

  // 同時に何本か走らせる（直列だと待ち時間ばかりになる）
  let 次 = 0;
  const 走者 = Array.from({ length: Math.min(同時に読む数, 対象.length) }, async () => {
    while (次 < 対象.length) {
      const i = 次; 次 += 1;
      await 一本(対象[i]);
    }
  });
  await Promise.all(走者);

  if (途中経過 && 溜め.length) 途中経過(溜め);
  if (覚え途中 && 覚え溜め数) 覚え途中(覚え溜め);
  if (進み) 進み({ 段階: '読み終えました', 済み: 対象.length, 全体: 対象.length });

  return {
    tracks,
    found: files.length,
    unreadable,
    hidden: skip.size,
    // ★外した曲の記録も持ち越す。一覧に出さないだけで、忘れはしない
    覚え書き: { ...新しい覚え書き, ...外したぶんの覚え書き },
    使い回し,
  };
}

