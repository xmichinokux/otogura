/**
 * フォルダを走査して、曲の一覧を作るところ。
 *
 * ★Electron から切り離してある。
 * ここに置けば Node だけで動かして確かめられる（画面を開かずに検査できる）。
 *
 * ─────────────────────────────────────────────────────────
 * ■ ★2026-08-25 全面的に作り直した。実測で作りが破綻していたため
 *
 * 本人のライブラリ: **171,085 曲 / 387 GB**（「数GB」ではなかった）。
 * 登録したらアプリが落ちた。測ったら理由がはっきりした。
 *
 *   アートワークを全曲ぶん持つ  → **17.8 GB**（落ちた直接の原因）
 *   ファイルを数えるだけ        → **297 秒**
 *
 * ★タグ読みの速さは、**初めて触るか / 一度読んだか**で桁が変わる。
 *
 *   初めて触るファイル  約 36 ms/曲 → 171,085 曲で **約 100 分**
 *   一度読んだファイル  約  1 ms/曲 → **約 3 分**
 *
 * ここには最初「絵つき 14.6ms → 絵なし 1.2ms。12 倍速い」と書いてあったが、
 * **この 2 つを混ぜて測っていた**（2 回目は OS がファイルを覚えている）。
 * 同じ設定でも、冷えていれば 36ms、温まっていれば 1ms になる。
 * 絵を読まない値打ちは**速さではなく、17.8 GB を抱えないこと**にある。
 * ★速さを比べるときは、**どちらも初めて触るファイル**で測ること。
 *
 * ★落ちた直接の原因はアートワーク。
 * 全曲の絵を base64 にしてメモリに置き、**一括で画面へ送っていた。**
 * 17.8 GB は載らない。
 *
 * ■ 直した点
 * 1. **アートワークを一覧に載せない。** 再生する曲のぶんだけ、その場で読む
 *    （速くなるからではない。**17.8 GB を抱えないため**。速さの差は 0%）
 * 2. **覚えておく。** パスと更新日時と大きさが同じなら、タグを読み直さない
 *    → 2 回目からは、変わったファイルだけ読む
 * 3. **少しずつ返す。** 見つかったそばから画面へ送る。全部そろうまで待たせない
 * 4. **同時に何本か読む。** 直列だと待ち時間ばかりになる
 * 5. **進み具合を出す。** 何も出ない時間を作らない
 *
 * ■ 守っていること（変えていない）
 * ・**ファイルを消す処理は書かない。**削除は「一覧から外すだけ」
 * ・アーティスト／アルバムが空の曲は Unknown にまとめる
 * ─────────────────────────────────────────────────────────
 */

