'use strict';

/**
 * 曲ごとの音量差をならす計算。
 *
 * ■ なぜ要るか（本人の希望 2026-08-24）
 * > 音源自体のボリュームが違うので音の大きさのバラツキが気になりました
 *
 * ■ どうするか
 * 曲の「平均的な大きさ（RMS）」を測り、**基準に合うだけ音量をかける**。
 * 小さく録れている曲は持ち上げ、大きい曲は下げる。ReplayGain と同じ考え方。
 *
 * ■ 音を割らないために
 * 持ち上げすぎると、いちばん大きい瞬間（ピーク）が振り切れて音が割れる。
 * **ピーク × 倍率が 1.0 を超えないところで頭打ち**にする。
 * 上げ下げの幅も ±12dB までに制限する（それ以上は元の録音が特殊なので触らない）。
 *
 * ここは純粋な計算だけにしてある（音の取り込みは画面側）。
 * そうしておくと、画面を開かずに数字で確かめられる。
 */

/** 基準の大きさ。-14 LUFS 前後が配信サービスの標準的な値なので、それに寄せた */
const 基準dB = -14;
/**
 * 上げ下げの上限。
 * ★実測で +12dB では足りず、静かな曲が頭打ちになった。
 * 音割れは「ピーク × 倍率 ≤ 1.0」で別に止めているので、ここは広げてよい。
 * それでも青天井にはしない（ほぼ無音の曲のノイズまで持ち上げないため）。
 */
const 最大dB = 20;

/** 二乗平均平方根（平均的な音の大きさ） */
function rmsを出す(samples) {
  if (!samples || !samples.length) return 0;
  let 合計 = 0;
  for (let i = 0; i < samples.length; i += 1) 合計 += samples[i] * samples[i];
  return Math.sqrt(合計 / samples.length);
}

/** いちばん大きい瞬間 */
function ピークを出す(samples) {
  let 最大 = 0;
  for (let i = 0; i < samples.length; i += 1) {
    const v = Math.abs(samples[i]);
    if (v > 最大) 最大 = v;
  }
  return 最大;
}

const dBにする = (比) => (比 > 0 ? 20 * Math.log10(比) : -Infinity);
const 倍率にする = (dB) => 10 ** (dB / 20);

/**
 * 測った値から、かけるべき倍率を出す。
 * @param rms   平均的な大きさ（0〜1）
 * @param ピーク いちばん大きい瞬間（0〜1）
 * @returns { 倍率, dB, 頭打ち } 頭打ち=音割れを避けて抑えたか
 */
function 倍率を決める(rms, ピーク) {
  if (!(rms > 0)) return { 倍率: 1, dB: 0, 頭打ち: false };

  let dB = 基準dB - dBにする(rms);
  // 上げ下げしすぎない
  dB = Math.max(-最大dB, Math.min(最大dB, dB));

  let 倍率 = 倍率にする(dB);
  let 頭打ち = false;

  // ★音が割れないところで止める。ピーク × 倍率 が 1.0 を超えないように
  if (ピーク > 0 && ピーク * 倍率 > 1) {
    倍率 = 1 / ピーク;
    dB = dBにする(倍率);
    頭打ち = true;
  }
  return { 倍率, dB, 頭打ち };
}

/**
 * 取り込んだ音の波形から、まとめて測る。
 *
 * ★静かなところを外して測る（ゲーティング）。
 * 全体をならして測ると、**無音や余韻の多い曲ほど「小さい曲」と判定され**、
 * 必要以上に持ち上げられる。実測でそうなった（効果音集で 22.5dB → 13.2dB までしか
 * 揃わず、上限で頭打ちになっていた）。
 * 実際の音量計（EBU R128）も、静かな部分を外して測る仕組みを持っている。
 *
 * やり方: 0.4 秒ごとの小さな塊に分けて測り、
 * **いちばん大きい塊から 20dB 以上落ちる塊を捨てて**から平均する。
 *
 * @param チャンネル Float32Array の配列（左右など）
 * @param 間引き   何サンプルおきに見るか。大きいほど速いが粗い
 * @param サンプル率 塊の長さを決めるのに使う
 */
function 測る(チャンネル, 間引き = 4, サンプル率 = 44100) {
  if (!チャンネル || !チャンネル.length) return { rms: 0, ピーク: 0 };

  const 塊の長さ = Math.max(1, Math.floor((サンプル率 * 0.4) / 間引き));
  const 塊 = [];
  let 最大 = 0;

  // まず塊ごとの大きさを出す
  let 和 = 0;
  let 数 = 0;
  for (const ch of チャンネル) {
    for (let i = 0; i < ch.length; i += 間引き) {
      const v = ch[i];
      和 += v * v;
      数 += 1;
      const a = Math.abs(v);
      if (a > 最大) 最大 = a;
      if (数 >= 塊の長さ) { 塊.push(Math.sqrt(和 / 数)); 和 = 0; 数 = 0; }
    }
  }
  if (数 > 0) 塊.push(Math.sqrt(和 / 数));
  if (!塊.length) return { rms: 0, ピーク: 最大 };

  // 静かな塊を外す。いちばん大きい塊から 20dB 下を境にする
  const 塊の最大 = Math.max(...塊);
  const 境 = 塊の最大 * 倍率にする(-20);
  const 残った = 塊.filter((v) => v >= 境);
  const 使う = 残った.length ? 残った : 塊;      // 全部外れたら仕方なく全部使う

  const 二乗和 = 使う.reduce((a, v) => a + v * v, 0);
  return { rms: Math.sqrt(二乗和 / 使う.length), ピーク: 最大 };
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { rmsを出す, ピークを出す, 倍率を決める, 測る, 基準dB, 最大dB };
}
