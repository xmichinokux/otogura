/*
 * ジャンル名をまとめる。
 *
 * ■ なぜ要るか（2026-08-30 本人の希望）
 *   > ジャンル名が適当に付けられたデータがたくさんあって困ってるんですが、
 *   > AI がいい感じにまとめてくれる機能って作れますか？
 *
 * ★実測してから作った。この蔵書（86,044 曲）のジャンル名は 98 種類。
 * 荒れ方は「打ち間違い」ではなく、**粒の大きさがばらばら**なことだった。
 *
 *   ・同じ系統が別々の名前に散っている（大きいものから小さいものまで）
 *   ・大文字小文字だけ違うものが 3 組（合わせて 11,596 曲）
 *   ・1 つの欄に複数を詰め込んだもの（区切り文字入り）が 6 件
 *   ・ジャンルではないもの（レーベル名など）が混ざっている
 *   ・「ジャンル名無し」という**文字列**が 2,585 曲
 *
 * 全部並べても 1,448 文字（≒ 414 トークン）。**一度に渡しきれる。**
 * 86,044 曲を走らせる話ではない。名前の一覧を渡すだけで済む。
 *
 * ■ ★消さない・書き換えない
 * 元のジャンル名には触らない。mp3 のタグも書き換えない。
 * まとめは**別の層**として覚えておき、見るときに重ねる。
 * 気に入らなければ、まとめを捨てれば元通りになる。
 *
 * ■ ★AI の言うことをそのまま信じない
 * 手元に無い名前を返してくることがある。
 * 返事は必ず ジャンルの返事を整える() を通し、**手元にある名前だけ**を残す。
 */

/** 列のまとめ方と同じ規則（小文字にして比べる） */
/*
 * ★英語のときは、AI への頼み文も英語にする（2026-08-30）。
 * ★この 2 つは画面でも <script> で読むので、lang.js の 言 と名前がぶつからないよう
 * 別の名前で受ける。画面では大域の 言 を使う。
 */
const 言う = (typeof require === 'function')
  ? require('./lang').言
  : ((typeof 言 === 'function') ? 言 : ((s) => s));
const ジャンルの鍵 = (v) => String(v ?? '').toLocaleLowerCase('ja').trim();

/**
 * 蔵書のジャンル名を数える。
 * 小文字にして同一視し、字面は最初に出てきたものを代表にする（カラムと同じ）。
 */
function ジャンルを数える(tracks) {
  const 束 = new Map();
  for (const t of Array.isArray(tracks) ? tracks : []) {
    const 生 = String((t && t.genre) ?? '').trim();
    if (!生) continue;
    const k = ジャンルの鍵(生);
    if (!束.has(k)) 束.set(k, { 名: 生, 鍵: k, 曲数: 0 });
    束.get(k).曲数 += 1;
  }
  return [...束.values()].sort((a, b) => b.曲数 - a.曲数 || a.鍵.localeCompare(b.鍵));
}

/**
 * AI への頼み文。
 *
 * ★曲数を必ず添える。12,000 曲のものと 1 曲のものを同じ重みで扱われると、
 * 大きいほうが小さいほうに吸われる。**大きいものが親になるべき。**
 */
function ジャンルの頼み文(一覧) {
  const 表 = 一覧.map((g) => `${g.名}\t${g.曲数}`).join('\n');
  return [
    言う('あなたは音楽ライブラリの整理を手伝います。'),
    '',
    言う('下は、この人の手元にあるジャンル名と、その曲数です。'),
    言う('長いあいだに付け足されてきたので、**粒の大きさがばらばら**です。'),
    言う('大きな系統の名前と、その中の細かい呼び名が、同じ高さに並んでいます。'),
    '',
    言う('■ してほしいこと'),
    言う('これらを、**見て回りやすい大きさの親**にまとめてください。'),
    '',
    言う('・親の名前は、その集まりを最もよく言い表すものにする'),
    言う('　手元にある名前をそのまま親に使ってよい（曲数の多いものが親に向く）'),
    言う('・大文字小文字だけが違うものは、必ず同じ親にする'),
    言う('・1 つの欄に複数の名前が詰め込まれているものは、主なものの親に入れる'),
    言う('・打ち間違いや略号は、元の名前の親に入れる'),
    言う('・ジャンルではないもの（レーベル名、媒体の種類、意味の取れない短い符号、'),
    言う('　「ジャンル名が無い」という意味の文字列など）は、音楽の系統に混ぜず、'),
    言う('　それとわかる親にまとめる'),
    '',
    言う('■ 守ること'),
    言う('・★子の名前は、下の一覧にある文字列を**そのまま**書き写すこと。'),
    言う('　一覧に無い名前を作らないでください'),
    言う('・同じ名前を 2 つの親に入れないでください'),
    言う('・迷うものは、無理に大きな親へ入れず、そのままにしておいてください'),
    言う('　（親を作らなければ、その名前はそのまま残ります）'),
    言う('・★大きな系統をひとつに潰しすぎないでください。'),
    言う('　この人はその区別を使って聴いています。**探しやすさが目的**であって、'),
    言う('　名前を減らすことが目的ではありません'),
    '',
    言う('■ 親ごとに、なぜそうまとめたかを一行で添えてください'),
    言う('この人が見て、要らない親を外せるようにするためです。'),
    '',
    言う('■ 手元のジャンル名（名前／曲数）'),
    表,
  ].join('\n');
}

/**
 * AI の返事を、手元にある名前だけに整える。
 *
 * ★ここが要。手元に無い名前、二重に入った名前、空の親を落とす。
 * 落としたものは黙って捨てず、必ず 覚え書き に残して画面に出す。
 */
function ジャンルの返事を整える(返り, 一覧) {
  const ある = new Map();
  for (const g of 一覧) ある.set(g.鍵, g);

  const 使った = new Set();
  const 組 = [];
  const 落とした = { 手元に無い: [], 二重: [], 空の親: 0 };

  const 生の組 = (返り && Array.isArray(返り.組)) ? 返り.組 : [];
  for (const c of 生の組) {
    const 親 = String((c && c.親) ?? '').trim();
    if (!親) { 落とした.空の親 += 1; continue; }

    const 子 = [];
    let 曲数 = 0;
    for (const 生 of (Array.isArray(c.子) ? c.子 : [])) {
      const k = ジャンルの鍵(生);
      if (!k) continue;
      if (!ある.has(k)) { 落とした.手元に無い.push(String(生)); continue; }
      if (使った.has(k)) { 落とした.二重.push(ある.get(k).名); continue; }
      使った.add(k);
      子.push(k);
      曲数 += ある.get(k).曲数;
    }
    if (!子.length) { 落とした.空の親 += 1; continue; }
    組.push({ 親, 子, 曲数, 訳: String((c && c.訳) ?? '').trim() });
  }

  組.sort((a, b) => b.曲数 - a.曲数);

  /* どこにも入らなかった名前は、そのまま残る（まとめない、が答えのこともある） */
  const 残り = 一覧.filter((g) => !使った.has(g.鍵));

  return { 組, 残り, 落とした };
}

/**
 * 設定から読んだまとめを、信じられる形にする。
 * ★覚え書きは人の手でも直せる場所なので、読むたびに整える。
 */
function ジャンルのまとめを整える(v) {
  const o = (v && typeof v === 'object') ? v : {};
  const 使った = new Set();
  const 組 = [];
  for (const c of (Array.isArray(o.組) ? o.組 : [])) {
    const 親 = String((c && c.親) ?? '').trim();
    if (!親) continue;
    const 子 = [];
    for (const s of (Array.isArray(c.子) ? c.子 : [])) {
      const k = ジャンルの鍵(s);
      if (!k || 使った.has(k)) continue;
      使った.add(k);
      子.push(k);
    }
    if (!子.length) continue;
    組.push({ 親, 子, 訳: String((c && c.訳) ?? '').trim() });
  }
  return { 組, 作った日: typeof o.作った日 === 'string' ? o.作った日 : '' };
}

/** まとめから「小文字のジャンル名 → 親」の索引を作る */
function ジャンルの索引を作る(まとめ) {
  const m = new Map();
  for (const c of ((まとめ && Array.isArray(まとめ.組)) ? まとめ.組 : [])) {
    for (const k of (Array.isArray(c.子) ? c.子 : [])) m.set(ジャンルの鍵(k), c.親);
  }
  return m;
}

/**
 * その曲のジャンルを、まとめた名前にする。
 * ★どの親にも入っていなければ、**元の名前のまま**返す。
 * まとめていないものが消えると、一覧から曲が消えたように見える。
 */
function まとめた名(索引, genre) {
  const 生 = String(genre ?? '').trim();
  if (!生) return null;
  const 親 = 索引 && 索引.get(ジャンルの鍵(生));
  return 親 || 生;
}

// Node（本体・検査）と画面（<script> 読み込み）の両方で使えるようにしておく。
// 同じ処理を 2 か所に書くと、片方だけ直す事故になる。
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { ジャンルの鍵, ジャンルを数える, ジャンルの頼み文, ジャンルの返事を整える, ジャンルのまとめを整える, ジャンルの索引を作る, まとめた名 };
}
