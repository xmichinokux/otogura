/**
 * 言葉から木を生やす。
 *
 * ★返す形は、Resonance の書き出しと**同じ形**にする。
 * こうすると、読み込んだ木と生やした木が、その先はまったく同じ道を通る
 * （src/resonance.js の 突き合わせる がそのまま使える）。
 * 形を分けると、片方だけ直す事故になる。
 *
 * @returns { ok: true, 結果: { keyword, savedAt, nodes: [{name, genre, description, depth}] } }
 *        | { ok: false, error }
 */
async function 木を生やす({ キー, 言葉, 手元の演者 = [], 幅目盛, 蔵書 = null, すでにある = [], 強度目盛 }) {
  if (!キー) return { ok: false, error: 'APIキーが設定されていません' };
  if (typeof 言葉 !== 'string' || !言葉.trim()) return { ok: false, error: '言葉が空です' };

  let Anthropic; let z; let zodOutputFormat;
  try {
    Anthropic = require('@anthropic-ai/sdk').default ?? require('@anthropic-ai/sdk');
    ({ z } = require('zod'));
    ({ zodOutputFormat } = require('@anthropic-ai/sdk/helpers/zod'));
  } catch {
    return { ok: false, error: 'AI の部品が読み込めません' };
  }

  const かたち = z.object({
    nodes: z.array(z.object({
      name: z.string(),
      description: z.string(),
      depth: z.number(),
    })),
  });

  /* ★finally から見えるよう、try の外で宣言する */
  let 札 = null;
  try {
    const client = new Anthropic({ apiKey: キー });
    // ★流し込みで受ける（max_tokens 21,333 の壁を避ける。上の説明を参照）
    札 = 中断札を用意する();
    const 返り = await client.messages.stream({
      model: 使うモデル,
      /*
       * ★返事の上限。**考えたぶんも、ここに含まれる。**
       *
       * ■ 実地の不具合（2026-08-29）。本人からの報告:
       *   > carcassを対象幅最大、選出量最大で試したらエラーが出ました。
       *
       * 0.17.0 で effort を low → medium に上げたとき、**上限を上げ忘れた。**
       * そこへ 0.18.0 で名前を 60 → 90 個に増やしたので、
       * いちばん広いところで足りなくなった。実測:
       *
       *   幅5（名前 90 個）  返事に要る ≈ 5,400 ﾄｰｸﾝ / 前の上限 7,800
       *   → 残り 2,400 しか考えるぶんが無い。medium だと軽く超える
       *   → stop_reason が max_tokens になり「返事が長すぎて切れました」
       *
       * ★上限は**使った分だけ請求される**ので、大きめに取って損はしない。
       * 足りないと丸ごと無駄になる。ここはけちるところではない。
       * 名前 1 個 150 ﾄｰｸﾝ（余裕込み）＋ 考えるぶん 12,000。
       */
      max_tokens: Math.max(16000, 幅を読む(幅目盛).名前 * 150 + 12000),
      system: 木の頼み文(手元の演者, 幅を読む(幅目盛), 蔵書, すでにある, 強度を読む(強度目盛)),
      messages: [{ role: 'user', content: 言葉.trim() }],
      /*
       * ★ここだけ effort を上げた（2026-08-29 本人の指摘）。
       *   > 王道的なのが気になります。マニアックな文脈が苦手というか。
       *
       * 一覧から選ぶ仕事（気分・プレイリスト）は low でよい。決まった中から選ぶだけなので。
       * こちらは**記憶の奥から引き出す**仕事で、浅く考えると
       * 「まず思いつくもの」＝代表格が出る。そこが不満の正体だった。
       *
       * ★費用は 1 本 4 円ほどから、8 円ほどに上がる見込み（考えるぶん）。
       * 出てくるものが変わらなければ、low に戻すこと。
       */
      // ★深さも強度で決まる。遠いものを引き出すほど、深く考えさせる
      output_config: { effort: 強度を読む(強度目盛).effort, format: zodOutputFormat(かたち) },
    }, { signal: 札.signal }).finalMessage();
    if (返り.stop_reason === 'refusal') return { ok: false, error: 'AI が答えを断りました' };
    /*
     * ★何をすればいいかまで言う。「切れました」だけだと、
     * つまみを動かせばいいと分からない。
     */
    if (返り.stop_reason === 'max_tokens') {
      return { ok: false, error: '返事が長すぎて切れました。「対象の幅」を 1 つ狭めて、もう一度お試しください' };
    }
    const 出 = 返り.parsed_output;
    if (!出 || !Array.isArray(出.nodes)) return { ok: false, error: 'AI の返事を読み取れませんでした' };

    /*
     * ★形をそろえて返す。
     * genre は 'music' で固定する（音楽だけを頼んでいるので）。
     * 同じ名前は落とす。深さは 0〜3 に丸める。
     */
    // ★すでに挙げたものは、返ってきても落とす（頼んでも守らないことがある）
    const 見た = new Set(すでにある.map((n) => String(n).toLocaleLowerCase('ja').trim()));
    const nodes = [];
    for (const n of 出.nodes) {
      const name = (n && typeof n.name === 'string') ? n.name.trim() : '';
      if (!name) continue;
      const k = name.toLocaleLowerCase('ja');
      if (見た.has(k)) continue;
      見た.add(k);
      nodes.push({
        name,
        genre: 'music',
        description: (n && typeof n.description === 'string') ? n.description.trim() : '',
        depth: Number.isFinite(n.depth) ? Math.max(0, Math.min(3, Math.round(n.depth))) : 1,
      });
    }
    if (!nodes.length) return { ok: false, error: 'AI が名前を挙げませんでした' };
    return { ok: true, 結果: { keyword: 言葉.trim(), savedAt: new Date().toISOString(), nodes } };
  } catch (e) {
    /* ★自分で止めたときは、壊れたように見せない（2026-08-30 本人の希望） */
    if (止められたか(e)) return { ok: false, 止めた: true, error: '止めました' };
    const 名 = e && e.constructor ? e.constructor.name : '';
    if (名 === 'AuthenticationError') return { ok: false, error: 'APIキーが正しくないようです' };
    if (名 === 'RateLimitError') return { ok: false, error: '短い間に呼びすぎました' };
    if (名 === 'APIConnectionError') return { ok: false, error: 'つながりませんでした' };
    return { ok: false, error: (e && e.message) ? e.message : '不明な失敗' };
  } finally {
    中断札を片づける(札);
  }
}

