function 曲数を丸める(曲数, 候補数) {
  const n = Number.isFinite(候補数) ? Math.max(0, Math.floor(候補数)) : 0;
  const 望み = Number.isFinite(曲数) ? Math.round(曲数) : 作る曲数;
  return Math.max(1, Math.min(望み > 0 ? 望み : 作る曲数, n || 1));
}

/**
 * ジャンルの一覧を作る（件数の多い順）。
 * ★件数を付けるのは、AI に「そのジャンルがどれくらいあるか」を伝えるため。
 * 3 曲しかないジャンルばかり選ばれても、聴くものにならない。
 */
function ジャンル一覧を作る(tracks) {
  const 数 = new Map();
  for (const t of tracks) {
    const g = (t && t.genre ? String(t.genre) : '').trim();
    if (!g) continue;
    数.set(g, (数.get(g) ?? 0) + 1);
  }
  return [...数.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([名前, 件数]) => ({ 名前, 件数 }));
}

