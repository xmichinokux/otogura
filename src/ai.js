/*
 * ★つまみを触っていないときの値。上の段の真ん中から取る。
 * ここに数を直書きすると、段の表と食い違ったときに気づけない。
 */
const 候補の数 = 幅の段[既定の目盛 - 1].候補;
const 作る曲数 = 量の段[既定の目盛 - 1].曲数;

/** 長い名前は切る。200 曲ぶん積むので、1 行の長さが効く */
const 短く = (v, n) => { const s = String(v ?? ''); return s.length > n ? s.slice(0, n) + '…' : s; };

function プレイリストの頼み文(気分, 曲数, 響き = '', 演者の数 = 0) {
  return [
    'あなたは DJ です。その人の手元にある曲から、**流す順番に並べた一本**を組みます。',
    '',
    '■ その人が言った気分',
    気分,
    '',
    // ★Resonance で辿った名前。あれば差し込む（無ければ何も足さない）
    ...(響き ? [響き, ''] : []),
    '■ 決まり',
    `・候補から **${曲数} 曲**選び、**流す順に**並べてください`,
    '・番号は候補に**実際にある番号**だけ。無い番号は返さない。同じ番号を 2 回使わない',
    /*
     * ★「続けない」だけでは足りなかった（2026-08-29 本人の報告）:
     *   > AI DJの選曲で同じバンドのものがいくつかあるので
     *   > 選択肢が多い場合は同じバンドやアルバムは極力選ばないようにしたい
     * 「続けない」は隣り合わせを禁じるだけなので、1 曲おきに同じバンドが
     * 並んでも決まりは守られてしまう。**全体で何曲までか**を言う。
     *
     * ★候補の側でも散らしてある（画面の AIに渡す候補）。ここはその念押し。
     * 演者の数を渡すのは、**何曲までなら守れるか**を分からせるため。
     * 候補に 5 組しかいないのに「1 組 1 曲」と言われても、守りようがない。
     */
    ...(演者の数 >= 曲数
      ? ['・★**同じアーティストは 1 曲まで。** 同じアルバムも 1 曲まで',
        `　（候補には ${演者の数} 組いるので、${曲数} 曲すべて別の組にできます）`]
      : ['・★**同じアーティストに寄せない。**',
        `　候補には ${演者の数 || 0} 組しかいないので、どうしても重なります。`,
        '　**なるべく散らして**、同じ組が固まらないように。続けて 2 曲は並べない']),
    '・★ただ合う曲を並べるのではなく、**流れを作ってください。**',
    '　入りは軽く、中盤で上げて、終わりは落ち着かせる ―― といった起伏を意識する',
    '・「ひとこと」は日本語で 1 文、20 字程度。**なぜその位置にその曲を置いたか**',
    '・「題」は、この一本につける短い名前（日本語 15 字程度）',
  ].join('\n');
}

/**
 * プレイリストを作らせる。
 *
 * ★失敗しても例外を投げない。呼んだ側は、だめなら普通のシャッフルのままにする。
 *
 * @param 候補 [{ 番号, artist, title, album }]（画面側が 200 曲だけ選んで渡す）
 * @returns { ok: true, 結果: { 題, 並び: [{番号, ひとこと}] } } | { ok: false, error }
 */
async function プレイリストを作らせる({ キー, 気分, 候補, 曲数 = 作る曲数, 響き = '' }) {
  if (!キー) return { ok: false, error: 'APIキーが設定されていません' };
  if (typeof 気分 !== 'string' || !気分.trim()) return { ok: false, error: '気分が空です' };
  if (!Array.isArray(候補) || !候補.length) return { ok: false, error: '候補がありません' };

  const 頼む曲数 = 曲数を丸める(曲数, 候補.length);
  // 候補に何組の演者がいるか。頼み文で「何曲まで別々にできるか」を伝えるのに使う
  const 演者の数 = new Set(候補.map((c) => String(c.artist || '').toLocaleLowerCase('ja').trim()).filter(Boolean)).size;

  let Anthropic; let z; let zodOutputFormat;
  try {
    Anthropic = require('@anthropic-ai/sdk').default ?? require('@anthropic-ai/sdk');
    ({ z } = require('zod'));
    ({ zodOutputFormat } = require('@anthropic-ai/sdk/helpers/zod'));
  } catch {
    return { ok: false, error: 'AI の部品が読み込めません' };
  }

  const 表 = 候補
    .map((c) => `${c.番号}\t${短く(c.artist, 28)}\t${短く(c.title, 40)}\t${短く(c.album, 28)}`)
    .join('\n');
  const かたち = z.object({
    題: z.string(),
    並び: z.array(z.object({ 番号: z.number(), ひとこと: z.string() })),
  });

  try {
    const client = new Anthropic({ apiKey: キー });
    // ★流し込みで受ける（max_tokens 21,333 の壁を避ける。上の説明を参照）
    const 返り = await client.messages.stream({
      model: 使うモデル,
      /*
       * ★番号とひとことを曲数ぶん返させるので、ここは切り詰めない。
       * 足りないと途中で切れて、並びが尻切れになる。
       *
       * ★つまみで 80 曲まで伸びるようになったので、**固定値をやめた。**
       * 8000 のままだと、多めにしたときだけ「返事が長すぎて切れました」に
       * なる。1 曲あたり 30 ﾄｰｸﾝ見当のところを 220 取って、余裕を持たせる。
       */
      // ★考えたぶんも含まれるので、余裕を取る（上限は使った分だけの請求）
      max_tokens: Math.max(16000, 頼む曲数 * 220 + 8000),
      system: プレイリストの頼み文(気分.trim(), 頼む曲数, 響き, 演者の数),
      messages: [{ role: 'user', content: '■ 候補（番号／アーティスト／曲名／アルバム）\n' + 表 }],
      output_config: { effort: 'low', format: zodOutputFormat(かたち) },
    }).finalMessage();
    if (返り.stop_reason === 'refusal') return { ok: false, error: 'AI が答えを断りました' };
    if (返り.stop_reason === 'max_tokens') return { ok: false, error: '返事が長すぎて切れました。「選出の量」を 1 つ減らして、もう一度お試しください' };
    const 出 = 返り.parsed_output;
    if (!出) return { ok: false, error: 'AI の返事を読み取れませんでした' };
    return { ok: true, 結果: { ...並びを確かめる(出, 候補), 頼んだ曲数: 頼む曲数, 演者の数 } };
  } catch (e) {
    const 名 = e && e.constructor ? e.constructor.name : '';
    if (名 === 'AuthenticationError') return { ok: false, error: 'APIキーが正しくないようです' };
    if (名 === 'RateLimitError') return { ok: false, error: '短い間に呼びすぎました。少し待ってからもう一度' };
    if (名 === 'APIConnectionError') return { ok: false, error: 'つながりませんでした（ネットワークを確認してください）' };
    return { ok: false, error: (e && e.message) ? e.message : '不明な失敗' };
  }
}

/**
 * 返ってきた並びを、候補と照らし合わせる。
 *
 * ★ここも鵜呑みにしない。**候補に無い番号は返ってくる。**
 * そのまま使うと、無い曲を流そうとして止まる。
 * ・候補に無い番号は落とす
 * ・同じ番号が 2 回出たら、後のほうを落とす（同じ曲が 2 回流れないように）
 * ・落とした数は呼んだ側に返す。黙って短くしない
 */
function 並びを確かめる(生, 候補) {
  const ある = new Map(候補.map((c) => [c.番号, c]));
  const 見た = new Set();
  const 並び = [];
  let 落とした = 0;
  for (const 項 of (Array.isArray(生 && 生.並び) ? 生.並び : [])) {
    const n = 項 && typeof 項.番号 === 'number' ? 項.番号 : null;
    if (n === null || !ある.has(n) || 見た.has(n)) { 落とした += 1; continue; }
    見た.add(n);
    並び.push({ 番号: n, ひとこと: (項 && typeof 項.ひとこと === 'string') ? 項.ひとこと.trim() : '' });
  }
  const 題 = (生 && typeof 生.題 === 'string' && 生.題.trim()) ? 生.題.trim() : '';
  return { 題, 並び, 落とした };
}

/**
 * 同じ言葉の木を混ぜる。**古いほうを残して、新しいものを足す。**
 *
 * ■ 本人の報告（2026-08-29）
 *   > 一度resonance生成したものと同じ名前で生成しても元の結果と同じままだった
 *
 * 前は同じ言葉なら**入れ替え**ていた。AI が似た答えを返すと、
 * 中身が変わらないので「反映されていない」ようにしか見えなかった。
 * 足していく形にすれば、押すたびに広がる ―― 「もっと辿る」になる。
 *
 * ★曲がたくさん当たるジャンルで演者が足りない、という不便もこれで直せる:
 *   > resonanceで選出した曲が結果的に多いと選出するバンドが少なくなるのが不便
 *   （グラインドコアのように、手元に厚いところで起きる）
 *
 * ★名前が同じものは足さない（小文字にして比べる。3 カラムと同じ規則）。
 * ★辿った日は新しいほうにする。重みは「新しいほど強い」ので、
 *   足したのに古いままだと、押すたびに弱くなってしまう。
 */
function 木を混ぜる(古い, 新しい) {
  if (!新しい || !Array.isArray(新しい.nodes)) return 古い || 新しい;
  if (!古い || !Array.isArray(古い.nodes) || !古い.nodes.length) return 新しい;
  const そろえる = (v) => String(v == null ? '' : v).toLocaleLowerCase('ja').trim();
  const 済 = new Set(古い.nodes.map((n) => そろえる(n.name)));
  const 足す = [];
  for (const n of 新しい.nodes) {
    const k = そろえる(n.name);
    if (!k || 済.has(k)) continue;
    済.add(k);
    足す.push(n);
  }
  return {
    keyword: 新しい.keyword,
    savedAt: 新しい.savedAt,
    nodes: [...古い.nodes, ...足す],
  };
}

