/**
 * 目盛を段に直す。
 * ★範囲の外・数でないものは、黙って既定に寄せる。**例外を投げない。**
 * 設定ファイルを人が手で書き換えても、壊れないようにしておく。
 */
function 段を選ぶ(表, 目盛) {
  const n = Number.isFinite(目盛) ? Math.round(目盛) : 既定の目盛;
  return 表[Math.max(1, Math.min(目盛の数, n)) - 1];
}
