console.log('\n[3] ★AI の返事を、手元にある名前だけに濾す');
{
  const 返り = {
    組: [
      { 親: 'Hardcore', 子: ['Hardcore', 'New School', 'Youth Crew'], 訳: '同じ系統' },
      { 親: 'Grindcore', 子: ['Grindcore', 'GrindCore'], 訳: '字面だけの違い' },
      { 親: 'Black Metal', 子: ['Black Metal', 'BM'], 訳: '略号' },
      /* ★ここから先は、わざと壊した返事 */
      { 親: 'Death Metal', 子: ['Brutal Death Metal', 'Slam'], 訳: '手元に無い名前だけ' },
      { 親: 'かぶり', 子: ['Hardcore'], 訳: 'すでに他の親に入っている' },
      { 親: '', 子: ['ジャンル名無し'], 訳: '親の名前が空' },
      { 親: '空っぽ', 子: [], 訳: '子がいない' },
    ],
  };
  const 出 = genre.ジャンルの返事を整える(返り, 一覧);

  確認('★手元に無い名前だけの親は、丸ごと落ちる', !出.組.some((c) => c.親 === 'Death Metal'));
  確認(
    '★手元に無い名前を覚え書きに残す（黙って捨てない）',
    出.落とした.手元に無い.includes('Brutal Death Metal') && 出.落とした.手元に無い.includes('Slam'),
  );
  確認('★同じ名前を 2 つの親に入れさせない', !出.組.some((c) => c.親 === 'かぶり'));
  確認('★二重も覚え書きに残す', 出.落とした.二重.includes('Hardcore'));
  確認('親の名前が空なら落ちる', !出.組.some((c) => c.親 === '' || c.親 === 'ジャンル名無し'));
  確認('子がいない親は落ちる', !出.組.some((c) => c.親 === '空っぽ'));
  /*
   * ★4 つ。親の名前が空・子がいない のほかに、
   * 「子が全部手元に無かった」「子が全部よそに取られた」ぶんも、
   * 結果として子が 0 になるのでここに数える。
   */
  確認('落とした空の親を数えている', 出.落とした.空の親 === 4, '実際: ' + 出.落とした.空の親);

  確認('残った親は 3 つ', 出.組.length === 3, '実際: ' + 出.組.length);
  確認(
    '★親は曲数の多い順（探すときに上から見る）',
    出.組[0].親 === 'Hardcore' && 出.組[0].曲数 === 200,
  );
  確認('大文字小文字の違いを吸って 50 曲になる', 出.組.find((c) => c.親 === 'Grindcore').曲数 === 50);

  /*
   * ★どこにも入らなかった名前は「残り」に出す。
   * まとめないという答えもある。黙って消えるのがいちばん困る。
   */
  const 残りの鍵 = 出.残り.map((g) => g.鍵);
  確認(
    '★どの親にも入らなかった名前は、残りとして出る',
    残りの鍵.includes('a389 recordings') && 残りの鍵.includes('ジャンル名無し'),
  );
  確認(
    '★手元のジャンルは、まとめたものと残りで必ず全部',
    出.組.reduce((s, c) => s + c.子.length, 0) + 出.残り.length === 一覧.length,
  );
}

