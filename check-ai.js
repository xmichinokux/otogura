    let n = 1;
    for (let a = 0; a < 2; a += 1) {
      for (let b = 0; b < 4; b += 1) {
        狭い候補.push({ 番号: n, artist: "演者" + a, album: "盤" + a + "-" + b, title: "曲" + n });
        n += 1;
      }
    }
    const 生 = { 題: "x", 並び: [1, 2, 3, 5, 6].map((番号) => ({ 番号, ひとこと: "" })) };
