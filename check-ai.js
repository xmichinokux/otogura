    確認('★蔵書に寄せるな、と毎回 言う',
      /そこに寄せて選ぶと、軸から外れます/.test(文)
        && /そこに寄せて選ぶと、軸から外れます/.test(木の頼み文([{ 名前: 'X', 曲数: 1 }], 幅を読む(2), null, [], 強度を読む(1), false)),
      '持っている名前に引きずられると、確かめる候補が出ません');
