    確認('★候補に無い番号は落とす', !r.並び.some((x) => x.番号 === 99), JSON.stringify(r.並び));
    確認('★同じ番号を 2 回使わせない', r.並び.filter((x) => x.番号 === 2).length === 1, JSON.stringify(r.並び));
    確認('通ったものは順番どおり', r.並び.map((x) => x.番号).join(',') === '2,1', JSON.stringify(r.並び));
