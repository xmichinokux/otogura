'use strict';

/*
 * 「自分の音源」の検査。
 *
 * ■ 本人の話（2026-08-30）
 *   > 自分のバンドで作曲途中のデータがたくさんあって
 *   > それが読み込まれてるんです。これはシャッフルの対象にされたくない
 *   > というのがありました。それで、タグなしを表示しないとか、
 *   > そういうことを考えていたという経緯がありました。
 *   > （そのあと、自分のバンドを 4 組ぶん挙げてもらった）
 *
 * ★これまで「タグ無しを隠す」でやろうとしていたが、半分しか効いていなかった。
 * 実測: 本人の 4 バンドで 453 曲。うち 219 曲にはタグが付いていて、
 * タグ無しを隠すで消えるのは **48% だけ**だった。
 *
 * ★ここで見張るのは 3 つ。
 *
 *  1. **曲を消さない。一覧からも消さない。** 押せば鳴る。
 *     くじと AI の候補に入らないだけ。
 *  2. **演者名の完全一致**であること。
 *     部分一致にすると、その名前を含む別のバンドを巻き込む。
 *  3. くじ・AI DJ・Resonance の**すべて**で効いていること。
 *     どれか 1 つ抜けると、そこからだけ作りかけが漏れる。
 */

const fs = require('node:fs');
const path = require('node:path');

let 落ちた = 0;
function 確認(題, 真, 補) {
  console.log((真 ? '  OK   ' : '  NG   ') + 題 + (真 || !補 ? '' : ' ― ' + 補));
  if (!真) 落ちた += 1;
}

const 画面 = fs.readFileSync(path.join(__dirname, 'src/renderer.js'), 'utf8');
const 本体 = fs.readFileSync(path.join(__dirname, 'src/main.js'), 'utf8');
const 橋 = fs.readFileSync(path.join(__dirname, 'src/preload.js'), 'utf8');
/* ★註釈を落とした写し。「呼んでいるか」はこちらで見る（消したのに通る事故を防ぐ） */
const 素 = 画面.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');

const 切る = (名) => {
  const 頭 = 画面.indexOf(`function ${名}(`);
  if (頭 < 0) throw new Error(名 + ' が無い');
  return 画面.slice(頭, 画面.indexOf(String.fromCharCode(10) + '}', 頭) + 2);
};

console.log('[1] ★演者名の完全一致か（別のバンドを巻き込まないか）');
{
  /*
   * ★実物どおりの仕込み。
   * ★台の名前は作り話。実物は「短い一語の名前」で、
   * それを含む別のバンドが手元にあった。
   * 部分一致で当てると、後者の 10 曲まで消える。
   */
  let 自分の音源 = new Set(['nightfall', 'quiet room']);
  const 小文字 = (v) => String(v).toLocaleLowerCase('ja');
  void 自分の音源; void 小文字;
  // eslint-disable-next-line no-eval
  const 自分のか = eval(切る('自分のか') + String.fromCharCode(10) + '自分のか');

  確認('自分のバンドは当たる', 自分のか({ artist: 'Nightfall' }) === true);
  確認('大文字小文字が違っても当たる', 自分のか({ artist: 'NIGHTFALL' }) === true);
  確認('前後の空白があっても当たる', 自分のか({ artist: '  Nightfall  ' }) === true);
  確認(
    '★Hour Of Nightfall（名前を含む別のバンド）は当たらない',
    自分のか({ artist: 'Hour Of Nightfall' }) === false,
    '部分一致にすると、実測で 10 曲を巻き込みます',
  );
  確認('★名前の一部が同じだけのものも当たらない', 自分のか({ artist: 'Nightfall Stare' }) === false);
  確認('演者名が無くても落ちない', 自分のか({}) === false);
  確認('曲そのものが無くても落ちない', 自分のか(null) === false);

  自分の音源 = new Set();
  確認('★1 つも登録していなければ、何も当たらない', 自分のか({ artist: 'Nightfall' }) === false);
}

console.log('\n[2] ★曲を消さない。一覧からも消さない');
{
  確認(
    '★見える曲() には手を入れていない（一覧からは消さない）',
    !/function 見える曲\(\)[\s\S]{0,200}自分のか/.test(画面),
    '一覧から消すのは「一覧から外す」の役目です。混ぜないこと',
  );
  確認(
    '★絞る() にも手を入れていない',
    !/function 絞る\(level\)[\s\S]{0,600}自分のか/.test(画面),
  );
  確認(
    '★曲やファイルを消す処理を足していない',
    !/unlink|rm\(|削除/.test(切る('自分のか')),
  );
  確認(
    '★一覧では、それと分かるようにする',
    /自分のか\(t\)\) tr\.classList\.add\('mine'\)/.test(素),
    '見た目が同じだと、なぜくじに来ないのか分かりません',
  );
  確認(
    '★消したようには見せない（薄くするだけ）',
    /tr\.mine td \{ opacity/.test(fs.readFileSync(path.join(__dirname, 'src/index.html'), 'utf8')),
  );
}

console.log('\n[3] ★くじ・AI のすべてで効いているか（1 つでも抜けるとそこから漏れる）');
{
  確認(
    '★AI DJ / Resonance の候補から外している',
    /const 母集団 = 組む範囲\(\)\.filter[\s\S]{0,160}!自分のか\(t\)/.test(素),
    'ここが抜けると、作りかけが一本に混ざります',
  );
  確認(
    '★シャッフルのくじから外している（その 1）',
    /const くじ列 = 鳴る列\.filter[\s\S]{0,120}!自分のか\(x\)/.test(素),
  );
  確認(
    '★シャッフルのくじから外している（その 2）',
    /const 候補 = 列\.filter[\s\S]{0,120}!自分のか\(t\)/.test(素),
  );
  /*
   * ★シャッフル除外 が効いているところと、同じ数だけ 自分のか が効いていること。
   * 新しいくじの引き方が増えたのに、こちらだけ足し忘れる ―― を捕まえる。
   */
  const 除外の数 = (素.match(/!シャッフル除外\.has\(/g) || []).length;
  const 自分の数 = (素.match(/!自分のか\(/g) || []).length;
  確認(
    '★シャッフル除外が効く場所すべてに、自分の音源も効いている',
    自分の数 >= 除外の数,
    `シャッフル除外 ${除外の数} か所 / 自分の音源 ${自分の数} か所`,
  );
}

console.log('\n[4] 覚えるところ');
{
  確認(
    '★覚えるのは演者名（曲のパスではない）',
    /自分の音源: Array\.isArray\(v\.自分の音源\)/.test(本体),
    'パスで覚えると、走査し直したぶんがまた混ざります',
  );
  確認(
    '★読むときに小文字にそろえる',
    /自分の音源[\s\S]{0,240}toLocaleLowerCase\('ja'\)/.test(本体),
  );
  確認(
    '★重なりを潰す',
    /自分の音源[\s\S]{0,200}new Set\(/.test(本体),
  );
  確認('本体に受け口がある', /ipcMain\.handle\('own:set'/.test(本体) && /ipcMain\.handle\('own:get'/.test(本体));
  確認('橋が通してある', 橋.includes('own:set') && 橋.includes('own:get'));
  確認(
    '★起動時に読み戻している',
    素.includes('自分の音源 = new Set(await window.mp3.自分の音源を取る())'),
    '読まないと、閉じるたびに戻ってしまいます',
  );

  /* ★覚え書きが壊れていても落ちないか */
  const 頭 = 本体.indexOf('自分の音源: Array.isArray(v.自分の音源)');
  const 素片 = 本体.slice(頭, 頭 + 320);
  // eslint-disable-next-line no-eval
  const 読む = eval('(v) => ({ ' + 素片.slice(0, 素片.indexOf('        : [],') + 13) + ' })');
  let 落ちない = true;
  for (const v of [{}, { 自分の音源: null }, { 自分の音源: 'あ' }, { 自分の音源: [1, null, 'A', 'a', ' A '] }]) {
    try { if (!Array.isArray(読む(v).自分の音源)) 落ちない = false; } catch { 落ちない = false; }
  }
  確認('★壊れた覚え書きでも落ちない', 落ちない);
  確認(
    '★大文字と小文字と空白違いは、1 つにまとまる',
    読む({ 自分の音源: ['A', 'a', ' A '] }).自分の音源.length === 1,
    '実際: ' + JSON.stringify(読む({ 自分の音源: ['A', 'a', ' A '] }).自分の音源),
  );
  確認(
    '★文字でないものは落とす',
    !読む({ 自分の音源: [1, null, {}, 'x'] }).自分の音源.some((x) => typeof x !== 'string'),
  );
}

console.log('\n[5] 印を付けるところ（まとめて／戻せる）');
{
  確認(
    '★選んだ曲から、演者をまとめて拾う',
    /const 選んだ演者 = new Set\(\)/.test(素),
    '1 曲ずつでは、実測 453 曲を相手にできません',
  );
  確認(
    '★入れるボタンと戻すボタンが、両方ある',
    /自分の音源を変える\(まだ, true\)/.test(素) && /自分の音源を変える\(入っている, false\)/.test(素),
    '戻せない印は、押すのが怖くなります',
  );
  確認(
    '★押す前に、何曲が対象かを見せる',
    /const 曲数 = \(演者\) => tracks\.filter/.test(素),
  );
  確認(
    '★入れる前に確かめる',
    /まだ\.length[\s\S]{0,600}await 確かめる\(/.test(素),
  );
  確認(
    '★何が起きるかを、そこに書いてある',
    /一覧には残ります。押せば鳴ります/.test(画面)
      && /曲は消えません。あとから戻せます/.test(画面),
    '「消える」と思わせないこと',
  );
}

console.log('');
if (落ちた) { console.log(`★${落ちた} 個 落ちました`); process.exit(1); }
console.log('すべて通りました');
