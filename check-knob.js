  確認('曲数が増える', 増える(曲数), 曲数.join(' → '));
  /*
   * ★範囲の外は、黙って端に寄せる。**例外を投げない。**
   * 設定ファイルを人が手で書き換えても、アプリが開かなくなってはいけない。
   */
  確認('0 は最小に寄る', ai.幅を読む(0).候補 === 候補[0]);
  確認('999 は最大に寄る', ai.幅を読む(999).候補 === 候補[候補.length - 1]);
