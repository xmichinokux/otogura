console.log('\n[5] 曲数を増やしたとき、返事の上限が足りるか');
/*
 * ■ ここを固定値のままにすると、**多めにしたときだけ**壊れる。
 * 「返事が長すぎて切れました」になり、原因がつまみだと分からない。
 * 1 曲は { 番号, ひとこと20字 } で 30 ﾄｰｸﾝ見当。余裕を見て数える。
 */
{
  const 本 = fs.readFileSync(path.join(__dirname, 'src/ai.js'), 'utf8');
  const m = /max_tokens: Math\.max\((\d+), 頼む曲数 \* (\d+) \+ (\d+)\)/.exec(本);
  確認('max_tokens が曲数で伸びる', !!m, m ? '' : '固定値のままです');
  if (m) {
    const 出せる = (n) => Math.max(Number(m[1]), n * Number(m[2]) + Number(m[3]));
    const 要る = (n) => n * 30;
    for (const 目盛 of [1, 3, 5]) {
      const n = ai.量を読む(目盛).曲数;
      確認(`${n} 曲ぶんが入る`, 出せる(n) >= 要る(n) * 2, `上限 ${出せる(n)} / 要る ${要る(n)}`);
    }
  }
  const t = /max_tokens: Math\.max\((\d+), 幅を読む\(幅目盛\)\.名前 \* (\d+) \+ (\d+)\)/.exec(本);
  確認('木の max_tokens も名前の数で伸びる', !!t, t ? '' : '固定値のままです');
  if (t) {
    const n = ai.幅を読む(ai.目盛の数).名前;
    const 出せる = Math.max(Number(t[1]), n * Number(t[2]) + Number(t[3]));
    確認(`名前 ${n} 個ぶんが入る`, 出せる >= n * 70, `上限 ${出せる}`);
  }
}

