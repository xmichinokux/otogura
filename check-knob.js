console.log('\n[5] ★返事の上限が、考えるぶんまで含めて足りるか');
/*
 * ■ 実地の不具合（2026-08-29）。本人からの報告:
 *   > carcassを対象幅最大、選出量最大で試したらエラーが出ました。
 *
 * ★**考えたぶんも max_tokens に含まれる。** ここを見落としていた。
 * 0.17.0 で effort を low → medium に上げたとき上限を上げ忘れ、
 * 0.18.0 で名前を 60 → 90 個に増やして、いちばん広いところで足りなくなった。
 *
 *   幅5（名前 90 個）  返事に要る ≈ 5,400 ﾄｰｸﾝ / 前の上限 7,800
 *   → 考えるぶんが 2,400 しか残らない。medium だと軽く超える
 *
 * ★前の検査は「要るぶんの 1 倍あるか」しか見ていなかったので、**通っていた。**
 * 考えるぶんの席を数に入れていなかった。**3 倍**を求める。
 * ★上限は使った分だけの請求なので、大きめに取って損はしない。
 *   足りないと丸ごと無駄になる。けちるところではない。
 */
{
  const 本 = fs.readFileSync(path.join(__dirname, 'src/ai.js'), 'utf8');
  /* ★考えるぶんの席。返事そのものの何倍を空けておきたいか */
  const 考える席 = 3;

  const m = /max_tokens: Math\.max\((\d+), 頼む曲数 \* (\d+) \+ (\d+)\)/.exec(本);
  確認('一本の max_tokens が曲数で伸びる', !!m, m ? '' : '固定値のままです');
  if (m) {
    const 出せる = (n) => Math.max(Number(m[1]), n * Number(m[2]) + Number(m[3]));
    const 要る = (n) => n * 30;          // { 番号, ひとこと20字 } で 30 ﾄｰｸﾝ見当
    for (const 目盛 of [1, 3, 5]) {
      const n = ai.量を読む(目盛).曲数;
      確認(
        `${n} 曲 … 考えるぶんまで入る`,
        出せる(n) >= 要る(n) * 考える席,
        `上限 ${出せる(n)} / 返事 ${要る(n)} × ${考える席} = ${要る(n) * 考える席}`,
      );
    }
  }

  const t = /max_tokens: Math\.max\((\d+), 幅を読む\(幅目盛\)\.名前 \* (\d+) \+ (\d+)\)/.exec(本);
  確認('木の max_tokens が名前の数で伸びる', !!t, t ? '' : '固定値のままです');
  if (t) {
    const 出せる = (n) => Math.max(Number(t[1]), n * Number(t[2]) + Number(t[3]));
    const 要る = (n) => n * 60;          // { name, description20字, depth } で 60 ﾄｰｸﾝ見当
    for (const 目盛 of [1, 3, 5]) {
      const n = ai.幅を読む(目盛).名前;
      確認(
        `名前 ${n} 個 … 考えるぶんまで入る`,
        出せる(n) >= 要る(n) * 考える席,
        `上限 ${出せる(n)} / 返事 ${要る(n)} × ${考える席} = ${要る(n) * 考える席}`,
      );
    }
  }

  /*
   * ★深く考えさせるところは、とくに席が要る。
   * effort を上げるなら、上限も上げる ―― それを機械に見張らせる。
   */
  const 木の所 = 本.slice(本.indexOf('async function 木を生やす'));
  if (/effort: 'medium'|effort: 'high'/.test(木の所) && t) {
    const n = ai.幅を読む(ai.目盛の数).名前;
    const 出せる = Math.max(Number(t[1]), n * Number(t[2]) + Number(t[3]));
    確認(
      '★深く考えさせるぶん、上限に余裕がある',
      出せる >= 16000,
      `上限 ${出せる}（考えるぶんは数千ﾄｰｸﾝ出ます）`,
    );
  }

  /* 切れたときに、何をすればいいか言うか */
  確認(
    '★切れたら、つまみを動かすよう案内する',
    /「対象の幅」を 1 つ狭めて/.test(本) && /「選出の量」を 1 つ減らして/.test(本),
    '「切れました」だけだと、つまみを動かせばいいと分かりません',
  );
}

